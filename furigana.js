// 長い語から先に処理し、単語の一部だけに読みが付くのをできるだけ防ぎます。
const READINGS = [...new Map(READING_PAIRS.filter(Boolean)).entries()]
  .filter(([word, reading]) => /[\u3400-\u9fff]/.test(word) && word !== reading)
  .sort((a, b) => b[0].length - a[0].length);

const MATCHER = new RegExp(READINGS.map(([word]) => word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'OPTION', 'RUBY', 'RT', 'RP', 'CODE', 'PRE']);

function makeRuby(word, reading) {
  const ruby = document.createElement('ruby');
  ruby.className = 'auto-furigana';
  ruby.append(document.createTextNode(word));
  const rt = document.createElement('rt');
  rt.textContent = reading;
  ruby.append(rt);
  return ruby;
}

function furiganizeTextNode(node) {
  if (!node.isConnected || !node.nodeValue || !/[\u3400-\u9fff]/.test(node.nodeValue)) return;
  const parent = node.parentElement;
  if (!parent || SKIP_TAGS.has(parent.tagName) || parent.closest('ruby,script,style,textarea,input,option,code,pre,[data-no-furigana]')) return;
  const source = node.nodeValue;
  MATCHER.lastIndex = 0;
  if (!MATCHER.test(source)) return;
  MATCHER.lastIndex = 0;
  const fragment = document.createDocumentFragment();
  let cursor = 0;
  for (const match of source.matchAll(MATCHER)) {
    if (match.index > cursor) fragment.append(document.createTextNode(source.slice(cursor, match.index)));
    const pair = READINGS.find(([word]) => word === match[0]);
    if (pair) fragment.append(makeRuby(pair[0], pair[1]));
    cursor = match.index + match[0].length;
  }
  if (cursor < source.length) fragment.append(document.createTextNode(source.slice(cursor)));
  node.replaceWith(fragment);
}

export function enableFurigana() {
  const processTree = (root) => {
    if (root.nodeType === Node.TEXT_NODE) {
      furiganizeTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE && (SKIP_TAGS.has(root.tagName) || root.closest?.('ruby,[data-no-furigana]'))) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(furiganizeTextNode);
  };

  processTree(document.body);
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') processTree(record.target);
      for (const node of record.addedNodes || []) processTree(node);
    }
  });
  observer.observe(document.body, {subtree:true, childList:true, characterData:true});
}
